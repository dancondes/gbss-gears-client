function slugifySegment(value) {
    return String(value || '')
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '')
}

export function buildFormsMenuPath(groupDescription, subgroupDescription, name) {
    const segments = [groupDescription, subgroupDescription, name]
        .map(slugifySegment)
        .filter(Boolean)

    return `/${segments.join('/')}`
}

function getMenuIcon(name) {
    return MENU_ICON[name] || DEFAULT_ICON
}

export function getSidebarIcon(name) {
    return SIDEBAR_ICON[name] || DEFAULT_SIDEBAR_ICON
}

function isAccessible(menuAccess) {
    if (!menuAccess || typeof menuAccess !== 'object') {
        return false
    }

    return Number(menuAccess.id) !== 3
}

function filterAccessibleRows(formsMenuResponse) {
    return formsMenuResponse.filter(function (row) {
        return isAccessible(row.access)
    })
}

export function convertFormsMenuResponseToMenuItems(formsMenuResponse) {
    if (!Array.isArray(formsMenuResponse)) {
        return []
    }

    const visibleRows = filterAccessibleRows(formsMenuResponse)
    const groupedMenus = new Map()

    visibleRows.forEach(function (row) {
        if (!row || !row.Group || !row.SubGroup || !row.Name) {
            return
        }

        const groupId = row.Group.id || row.Group.description
        const subgroupId = row.SubGroup.id || row.SubGroup.description

        if (!groupedMenus.has(groupId)) {
            groupedMenus.set(groupId, {
                name: row.Group.description,
                order: row.Order,
                subgroups: new Map()
            })
        }

        const groupEntry = groupedMenus.get(groupId)
        if (typeof groupEntry.order !== 'number' || row.Order < groupEntry.order) {
            groupEntry.order = row.Order
        }

        if (!groupEntry.subgroups.has(subgroupId)) {
            groupEntry.subgroups.set(subgroupId, {
                name: row.SubGroup.description,
                order: row.Order,
                items: []
            })
        }

        const subgroupEntry = groupEntry.subgroups.get(subgroupId)
        if (typeof subgroupEntry.order !== 'number' || row.Order < subgroupEntry.order) {
            subgroupEntry.order = row.Order
        }

        subgroupEntry.items.push(row)
    })

    return Array.from(groupedMenus.values()).map(function (groupEntry) {
        const submenu = Array.from(groupEntry.subgroups.values())
            .sort(function (left, right) {
                return left.order - right.order
            })
            .map(function (subgroupEntry) {
                const childItems = subgroupEntry.items
                    .slice()
                    .sort(function (left, right) {
                        return left.Order - right.Order
                    })
                    .map(function (row) {
                        const path = buildFormsMenuPath(row.Group.description, row.SubGroup.description, row.Name)
                        const action = ACTION_MAP[path]
                        const item = {
                            name: row.Name,
                            icon: getMenuIcon(row.Name)
                        }

                        if (action) {
                            item.action = action
                        } else {
                            item.path = path
                        }

                        return item
                    })

                return {
                    name: subgroupEntry.name,
                    submenu: childItems
                }
            })

        return {
            name: groupEntry.name,
            submenu: submenu
        }
    })
}
